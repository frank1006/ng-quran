#!/usr/bin/env node
/**
 * Writes src/app/core/public-env.ts from environment variables, before every build and dev
 * server start (npm "prebuild" / "prestart"). Only values that are public by design go in it:
 * they end up in the app's JavaScript for anyone to read.
 *
 *   SUPABASE_URL              the project's URL
 *   SUPABASE_PUBLISHABLE_KEY  the publishable (public) key, never the secret key
 *
 * On Vercel they come from the project's env vars; locally from the environment or .env.local.
 * The file is git-ignored, so no key is committed. Missing values are written as '' (sign-in then
 * shows as unavailable instead of the build failing).
 */
import { existsSync } from 'node:fs';
import { writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
if (existsSync(join(ROOT, '.env.local'))) process.loadEnvFile(join(ROOT, '.env.local'));

const url = process.env.SUPABASE_URL ?? '';
const publishableKey = process.env.SUPABASE_PUBLISHABLE_KEY ?? '';
if (/^sb_secret_|service_role/.test(publishableKey)) {
  console.error('✗ SUPABASE_PUBLISHABLE_KEY holds a secret key. Use the publishable key.');
  process.exit(1);
}

await writeFile(
  join(ROOT, 'src/app/core/public-env.ts'),
  `// Generated by scripts/write-public-env.mjs: do not edit or commit. Public values only.
export const PUBLIC_ENV = {
  supabaseUrl: ${JSON.stringify(url)},
  supabasePublishableKey: ${JSON.stringify(publishableKey)},
};
`,
);
console.log(`public-env: Supabase ${url && publishableKey ? 'configured' : 'NOT configured (sign-in unavailable)'}`);
