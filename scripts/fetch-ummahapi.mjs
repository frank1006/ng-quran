/**
 * Saves UmmahAPI's reference data (https://ummahapi.com, offered free as sadaqah jariah) into
 * api/_lib/, so QuranFlow AI answers from a fixed, reviewed copy instead of a live service:
 * du'as (duas-data.ts), the 99 names of Allah (names-data.ts) and zakat rules (zakat-data.ts).
 * Only the data is kept (not the response's success/timestamp/api_info wrapper).
 * Re-run to refresh, then review the diff:
 *
 *   node scripts/fetch-ummahapi.mjs
 */
import { writeFileSync } from 'node:fs';

const API = 'https://ummahapi.com/api';
const today = new Date().toISOString().slice(0, 10);
const clean = (s) => String(s ?? '').replace(/\s+/g, ' ').trim();

async function data(path) {
  const response = await fetch(`${API}/${path}`);
  if (!response.ok) throw new Error(`${path}: HTTP ${response.status}`);
  const body = await response.json();
  if (!body.success || !body.data) throw new Error(`${path}: unexpected response`);
  return body.data;
}

function write(file, path, typeImport, exports) {
  writeFileSync(
    new URL(`../api/_lib/${file}`, import.meta.url),
    `// Generated by scripts/fetch-ummahapi.mjs from ${API}/${path} (UmmahAPI, offered as sadaqah jariah) on ${today}. Don't edit by hand.\n` +
      `${typeImport}\n\n` +
      Object.entries(exports).map(([name, [type, value]]) => `export const ${name}: ${type} = ${JSON.stringify(value, null, 2)};\n`).join('\n'),
  );
}

// Du'as
{
  const { duas: raw, categories: rawCategories } = await data('duas');
  const seen = new Set();
  const duas = [];
  for (const d of raw) {
    // The same du'a can sit in several categories (each with its own title, so kept), but a few repeat inside one category
    const key = `${d.category}:${clean(d.arabic).replace(/[ً-ٰٟ\s،,.]/g, '')}`;
    if (!key || seen.has(key)) continue;
    seen.add(key);
    duas.push({
      id: d.id,
      category: d.category,
      title: clean(d.title),
      arabic: clean(d.arabic),
      transliteration: clean(d.transliteration),
      translation: clean(d.translation),
      source: clean(d.source),
      repeat: Number(d.repeat) > 1 ? Number(d.repeat) : 1,
    });
  }
  const categories = rawCategories.map((c) => ({ id: c.id, name: clean(c.name), description: clean(c.description) }));
  write('duas-data.ts', 'duas', `import type { Dua, DuaCategory } from './duas';`, {
    DUA_CATEGORIES: ['DuaCategory[]', categories],
    DUAS: ['Dua[]', duas],
  });
  console.log(`${duas.length} du'as (${raw.length - duas.length} repeats skipped), ${categories.length} categories`);
}

// The 99 names of Allah
{
  const d = await data('asma-ul-husna');
  const names = d.names.map((n) => ({
    number: n.number,
    arabic: clean(n.arabic),
    transliteration: clean(n.transliteration),
    english: clean(n.english),
    meaning: clean(n.meaning),
  }));
  write('names-data.ts', 'asma-ul-husna', `import type { NameOfAllah } from './names';`, {
    NAMES_OF_ALLAH: ['NameOfAllah[]', names],
    NAMES_ABOUT: ['{ hadith: string; source: string }', { hadith: clean(d.hadith), source: clean(d.source) }],
  });
  console.log(`${names.length} names of Allah`);
}

// Zakat rules (live gold and silver prices are fetched when calculating, not stored)
{
  const d = await data('zakat/info');
  write('zakat-data.ts', 'zakat/info', `import type { ZakatInfo } from './zakat';`, { ZAKAT_INFO: ['ZakatInfo', d] });
  console.log('zakat info');
}
